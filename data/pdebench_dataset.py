"""
Generic 1D PDEBench dataset loader for the Padic Neural Operator (PNO).

Compatible with any 1D time-dependent PDE stored in HDF5 with a 'tensor' key
of shape  (N_samples, N_t, N_x).

This covers:
  - Official PDEBench files  (Burgers, Advection, Allen-Cahn, etc.)
  - Synthetic data generated by  data/pde_generators.py

The 1024-point spatial grid is *native* to the PNO architecture because
  1024 = 2^10 = p^n   (p=2, n=10)
which is exactly the p-adic domain Z/2^10Z that the Kozyrev wavelet
decomposition acts on.
"""

import torch
from torch.utils.data import Dataset
import h5py


class PDEBench1DDataset(Dataset):
    """
    Dataset loader for 1D PDE data stored as HDF5 with key ``tensor``.

    HDF5 layout expected::

        f['tensor']  ->  float32/float64 array,  shape (N_samples, N_t, N_x)

    Each sample is returned as:

    * ``x_in``  :  (4, N_x)    =  [IC, spatial_grid, left_bc, right_bc]
    * ``y``     :  (out_t, N_x) =  future states  t = ic_index+1 .. ic_index+out_t

    This matches the 4-channel input convention of all existing PNO configs.

    Parameters
    ----------
    h5_path     : str   Path to the HDF5 file.
    split       : str   ``'train'`` or ``'val'``.
    train_ratio : float Fraction of samples used for training (default 0.8).
    n_x         : int   Spatial resolution (default 1024 = 2^10, native to PNO).
    out_t       : int   Number of future time steps to predict (default 100).
    ic_index    : int   Time index of the initial condition (default 0).
    """

    def __init__(
        self,
        h5_path: str,
        split: str = "train",
        train_ratio: float = 0.8,
        n_x: int = 1024,
        out_t: int = 100,
        ic_index: int = 0,
    ):
        self.h5_path  = h5_path
        self.n_x      = n_x
        self.out_t    = out_t
        self.ic_index = ic_index

        with h5py.File(h5_path, "r") as f:
            shape     = f["tensor"].shape        # (N, T, X)
            n_total   = shape[0]
            n_t_avail = shape[1]
            n_x_file  = shape[2]

        assert n_x_file >= n_x, (
            f"File has {n_x_file} spatial points but n_x={n_x} was requested."
        )
        assert n_t_avail >= ic_index + out_t + 1, (
            f"File has only {n_t_avail} time steps; need at least "
            f"{ic_index + out_t + 1}  (ic_index={ic_index}, out_t={out_t})."
        )

        n_train = int(n_total * train_ratio)
        if split == "train":
            self.start_idx, self.end_idx = 0, n_train
        elif split == "val":
            self.start_idx, self.end_idx = n_train, n_total
        else:
            raise ValueError(f"split must be 'train' or 'val', got '{split}'")

        self.length = self.end_idx - self.start_idx

        # Spatial grid [0, 1] broadcast as a fixed input channel
        self.grid = torch.linspace(0, 1, n_x, dtype=torch.float32).unsqueeze(0)

    # ------------------------------------------------------------------
    def __len__(self) -> int:
        return self.length

    def __getitem__(self, idx: int):
        actual_idx = self.start_idx + idx

        with h5py.File(self.h5_path, "r") as f:
            # Read slice [ic_index .. ic_index + out_t] inclusive
            raw = f["tensor"][
                actual_idx,
                self.ic_index : self.ic_index + self.out_t + 1,
                : self.n_x,
            ]
            data = torch.from_numpy(raw).float()  # (out_t+1, N_x)

        # ---- build input tensor (4, N_x) ----
        x_ic   = data[0].unsqueeze(0)                                        # (1, N_x)
        left_bc  = torch.full((1, self.n_x), x_ic[0, 0].item(),  dtype=torch.float32)
        right_bc = torch.full((1, self.n_x), x_ic[0, -1].item(), dtype=torch.float32)
        x_in = torch.cat([x_ic, self.grid, left_bc, right_bc], dim=0)       # (4, N_x)

        # ---- target: next out_t steps ----
        y = data[1 : self.out_t + 1]                                         # (out_t, N_x)

        return x_in, y
